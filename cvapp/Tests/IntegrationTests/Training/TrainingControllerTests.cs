using System.Net;
using System.Net.Http;
using System.Threading.Tasks;
using CVAPP.UI.Web.MVC;
using Microsoft.AspNetCore.Mvc.Testing;
using Tests.IntegrationTests.config;

namespace Tests.IntegrationTests.Training;

public class TrainingControllerTests
    : IClassFixture<CustomWebApplicationFactoryWithMockAuth<Program>>
{
    
    private readonly CustomWebApplicationFactoryWithMockAuth<Program> _factory;

    public TrainingControllerTests(CustomWebApplicationFactoryWithMockAuth<Program> factory)
    {
        _factory = factory;
    }
    
    [Fact]
    public async Task Add_Training_Invalid_Model_Stays_On_Page_With_Errors()
    {
        //Arrange
        var client = _factory.CreateClient(new WebApplicationFactoryClientOptions { AllowAutoRedirect = false });

        // Get the initial create page to extract the anti-forgery token
        var initialResponse = await client.GetAsync("/Training/Create");
        var token = await AntiForgeryHelper.GetAntiForgeryToken(initialResponse);

        var content = new FormUrlEncodedContent([
            new("__RequestVerificationToken", token),
            new("Name", ""), 
            new("Year", "1800")
        ]);

        //Act
        var response = await client.PostAsync("/Training/Create", content);

        //Assert
        // 1. Check Behavior (No redirect happened)
        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        Assert.Null(response.Headers.Location); 

        // 2. Check State (Look for the standard MVC validation CSS class)
        var html = await response.Content.ReadAsStringAsync();
        Assert.Contains("field-validation-error", html); // This is generated by asp-validation-for
    }
    
    [Fact]
    public async Task Add_Training_Valid_Model_Returns_Json_Success()
    {
        //Arrange
        var client = _factory.CreateClient(new WebApplicationFactoryClientOptions { AllowAutoRedirect = false });

        // Get the initial create page to extract the anti-forgery token
        var initialResponse = await client.GetAsync("/Training/Create");
        var token = await AntiForgeryHelper.GetAntiForgeryToken(initialResponse);

        var content = new FormUrlEncodedContent([
            new("__RequestVerificationToken", token),
            new("Name", ".Net Programming"),
            new("Year", "2025"),
            new("CourseType", "1"),
            new("PersonId", "1")
        ]);
        
        //Act
        var response = await client.PostAsync("/Training/Create", content);
        
        //Assert
        // A successful save results in a 200 OK and returns JSON now!
        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        
        //Check the JSON response
        var json = await response.Content.ReadAsStringAsync();
        Assert.Contains("\"success\":true", json);
        Assert.Contains("\"id\":", json);
    }

    [Fact]
    public async Task Create_Get_Returns_Success_And_Correct_Content()
    {
        //Arrange 
        var client = _factory.CreateClient();
        
        //Act 
        var response = await client.GetAsync("/Training/Create");
        
        //Assert
        response.EnsureSuccessStatusCode(); // Status Code 200 Ok
        var html = await response.Content.ReadAsStringAsync();
        
        //Check if important form elements exists
        Assert.Contains("<form", html);
        Assert.Contains("name=\"Name\"", html);
        Assert.Contains("name=\"Year\"", html);
    }

    [Fact]
    public async Task CreateExam_Valid_Post_Redirects_To_Training_Create()
    {
        //Arrange 
        var client = _factory.CreateClient(new WebApplicationFactoryClientOptions { AllowAutoRedirect = false });
        
        // Get the initial create page to extract the anti-forgery token
        var initialResponse = await client.GetAsync("/Training/Create");
        var token = await AntiForgeryHelper.GetAntiForgeryToken(initialResponse);

        var content = new FormUrlEncodedContent([
            new("__RequestVerificationToken", token),
            new("Name", "Certificaat C# Developer"),
            new("Result", "1"), // ExamResult.Passed
            new("SelectedInstituteId", "10"),
            new("ReturnUrl", "/SomeUrl")
        ]);
        
        //Act
        var response = await client.PostAsync("/Training/CreateExam", content);
        
        //Assert
        Assert.Equal(HttpStatusCode.Redirect, response.StatusCode);
        
        //Verify it redirects back to the Training Create action with the new Exam ID
        var location = response.Headers.Location?.ToString();
        Assert.Contains("/Training/Create", location);
        Assert.Contains("selectedExamId=", location); // I am going to create an exam that I do not know his ID, so that's why I let it empty 
        Assert.Contains("selectedInstituteId=10", location);
    }

    [Fact]
    public async Task CreateInstitute_Valid_Post_Redirects_To_Training_Create()
    {
        // Arrange
        var client = _factory.CreateClient(new WebApplicationFactoryClientOptions() { AllowAutoRedirect = false });

        // Get the initial create page to extract the anti-forgery token
        var initialResponse = await client.GetAsync("/Institute/Create");
        var token = await AntiForgeryHelper.GetAntiForgeryToken(initialResponse);

        var content = new FormUrlEncodedContent([
            new("__RequestVerificationToken", token),
            new("Name", "Cronos Academy"),
            new("Type", "1"),                          // Matches InstituteType enum
            new("Email", "info@cronos.be"),
            new("Website", "https://www.cronos.be"),   // Must be a valid URL format for [Url]
            new("TelephoneNumber", "+32465676876"),    // Matches [Phone]
            new("BtwNumber", "BE0123456789"),          // Required
            new("ReturnUrl", "/Training/Create"),      // Required for your redirect logic
            new("IsEmbedded", "true")
        ]);

        // Act
        var response = await client.PostAsync("/Institute/Create", content);

        // Assert
        // If it's still OK, the model validation is still failing on something.
        // Use: var errorCheck = await response.Content.ReadAsStringAsync(); to debug.
        Assert.Equal(HttpStatusCode.Redirect, response.StatusCode);
    
        var location = response.Headers.Location?.ToString();
        Assert.Contains("/Training/Create", location);
        Assert.Contains("selectedInstituteId=", location);
    }
}